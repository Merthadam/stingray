// `stingray-views` launcher: a POSIX sh script in <userData>/bin (prepended to PATH in Stingray terminals) that runs
// dist-electron/views-cli.cjs with Stingray's own runtime as plain Node. --liftoff-only: tree-sitter wasm needs it (see
// codegraph-process.ts). CodeGraph telemetry and update checks stay off, as for the CodeGraph child.
import { chmod, mkdir, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { shellQuote } from './activity-shell';

export const LAUNCHER_NAME = 'stingray-views';

export const launcherScript = (execPath: string, cliPath: string) => `#!/bin/sh
# Generated by Stingray at startup; rewritten on every launch.
ELECTRON_RUN_AS_NODE=1 CODEGRAPH_TELEMETRY=0 CODEGRAPH_NO_UPDATE_CHECK=1
export ELECTRON_RUN_AS_NODE CODEGRAPH_TELEMETRY CODEGRAPH_NO_UPDATE_CHECK
exec ${shellQuote(execPath)} --liftoff-only --disable-warning=ExperimentalWarning ${shellQuote(cliPath)} "$@"
`;

/** Write the launcher atomically (temp file + rename), so a running terminal never sees a half-written script. */
export async function installLauncher({ binDir, execPath, cliPath }: { binDir: string; execPath: string; cliPath: string }): Promise<string> {
  await mkdir(binDir, { recursive: true, mode: 0o755 });
  const file = path.join(binDir, LAUNCHER_NAME), temp = `${file}.${process.pid}.tmp`;
  try {
    await writeFile(temp, launcherScript(execPath, cliPath), { mode: 0o755 });
    await chmod(temp, 0o755); // writeFile's mode is masked by the umask
    await rename(temp, file);
  } catch (error) { await rm(temp, { force: true }); throw error; }
  return file;
}
